create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score bigint not null,
  created_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

create or replace function public.submit_leaderboard_entry(
  p_player_name text,
  p_score bigint
)
returns public.leaderboard
language plpgsql
security definer
set search_path = public
as $$
declare
  new_entry public.leaderboard;
begin
  if char_length(trim(p_player_name)) not between 1 and 40 then
    raise exception 'Player name must be between 1 and 40 characters';
  end if;

  if p_score < 0 then
    raise exception 'Score must be non-negative';
  end if;

  insert into public.leaderboard (player_name, score)
  values (trim(p_player_name), p_score)
  returning * into new_entry;

  return new_entry;
end;
$$;

create or replace function public.get_leaderboard()
returns setof public.leaderboard
language sql
stable
security definer
set search_path = public
as $$
  select *
  from public.leaderboard
  order by score desc, created_at asc
  limit 100;
$$;

revoke all on function public.submit_leaderboard_entry(text, bigint) from public;
revoke all on function public.get_leaderboard() from public;
grant execute on function public.submit_leaderboard_entry(text, bigint) to anon;
grant execute on function public.get_leaderboard() to anon;
